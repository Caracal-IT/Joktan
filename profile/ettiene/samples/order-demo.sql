-- Tables and customers for the order approval demo (docs/demos/order-approval.md).
-- Run against the demo database on Data / Database; safe to run again.
CREATE TABLE IF NOT EXISTS public.customers (
  customer text PRIMARY KEY, name text NOT NULL, tier text NOT NULL DEFAULT 'standard', credit_limit numeric NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_ref text NOT NULL UNIQUE, customer text, priority text, total numeric, discount numeric, net numeric,
  status text NOT NULL DEFAULT 'received', decision text, comment text, approved_by text, po_number text,
  deliver_by date, notify_customer boolean, tracking text,
  created timestamptz NOT NULL DEFAULT now(), updated timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS public.order_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_ref text NOT NULL, sku text, description text, qty integer, unit_price numeric);
CREATE TABLE IF NOT EXISTS public.order_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_ref text, event text NOT NULL, detail jsonb, at timestamptz NOT NULL DEFAULT now());
