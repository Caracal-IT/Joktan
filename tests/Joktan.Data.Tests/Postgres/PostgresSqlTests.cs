using Joktan.Data.Postgres;
using Xunit;

namespace Joktan.Data.Tests.Postgres;

public class PostgresSqlTests
{
    [Fact]
    public void Names_are_quoted_with_their_quotes_doubled()
    {
        Assert.Equal("\"orders\"", PostgresSql.Quote("orders"));
        Assert.Equal("\"say \"\"hi\"\"\"", PostgresSql.Quote("say \"hi\""));
        Assert.Equal("\"my schema\".\"Table\"", PostgresSql.Table("my schema", "Table"));
    }

    [Fact]
    public void Schemas_and_tables_are_created_quoted()
    {
        Assert.Equal("CREATE SCHEMA \"shop\"", PostgresSql.CreateSchema("shop"));
        Assert.Equal("CREATE TABLE \"shop\".\"orders\" (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)", PostgresSql.CreateTable("shop", "orders", withId: true));
        Assert.Equal("CREATE TABLE \"shop\".\"notes\" ()", PostgresSql.CreateTable("shop", "notes", withId: false));
    }

    [Fact]
    public void A_column_gets_its_type_default_and_not_null_as_typed()
    {
        Assert.Equal("ALTER TABLE \"s\".\"t\" ADD COLUMN \"name\" text", PostgresSql.AddColumn("s", "t", new ColumnSpec("name", " text ")));
        Assert.Equal("ALTER TABLE \"s\".\"t\" ADD COLUMN \"at\" timestamptz DEFAULT now() NOT NULL",
            PostgresSql.AddColumn("s", "t", new ColumnSpec("at", "timestamptz", NotNull: true, Default: "now()")));
    }

    [Fact]
    public void Rows_are_read_as_text_after_their_ctid()
    {
        Assert.Equal("SELECT ctid::text, \"id\"::text, \"name\"::text FROM \"s\".\"t\" ORDER BY ctid LIMIT 200 OFFSET 0", PostgresSql.SelectRows("s", "t", ["id", "name"], [], 200, 0));
        Assert.Equal("SELECT ctid::text, \"a\"::text FROM \"s\".\"t\" ORDER BY \"k1\", \"k2\" LIMIT 50 OFFSET 100", PostgresSql.SelectRows("s", "t", ["a"], ["k1", "k2"], 50, 100));
        Assert.Equal("SELECT count(*) FROM \"s\".\"t\"", PostgresSql.Count("s", "t"));
    }

    [Fact]
    public void Values_are_parameters_and_never_part_of_the_text()
    {
        Assert.Equal("INSERT INTO \"s\".\"t\" (\"name\", \"qty\") VALUES ($1, $2)", PostgresSql.Insert("s", "t", ["name", "qty"]));
        Assert.Equal("INSERT INTO \"s\".\"t\" DEFAULT VALUES", PostgresSql.Insert("s", "t", []));
        Assert.Equal("DELETE FROM \"s\".\"t\" WHERE ctid = $1::tid", PostgresSql.Delete("s", "t"));
        Assert.Equal("UPDATE \"s\".\"t\" SET \"name\" = $1, \"qty\" = $2 WHERE ctid = $3::tid", PostgresSql.Update("s", "t", ["name", "qty"]));
    }

    [Fact]
    public void Drops_take_what_depends_on_them()
    {
        Assert.Equal("DROP SCHEMA \"shop\" CASCADE", PostgresSql.DropSchema("shop"));
        Assert.Equal("DROP TABLE \"s\".\"t\" CASCADE", PostgresSql.DropTable("s", "t"));
        Assert.Equal("ALTER TABLE \"s\".\"t\" DROP COLUMN \"c\" CASCADE", PostgresSql.DropColumn("s", "t", "c"));
    }

    [Fact]
    public void A_column_says_whether_it_may_be_null_its_default_and_key()
    {
        Assert.Equal(("no", "numbered for each row", "primary key"),
            (new TableColumn("id", "bigint", false, null, IsPrimaryKey: true, IsIdentity: true) is var id ? (id.NullText, id.DefaultText, id.KeyText) : default));
        Assert.Equal(("yes", "now()", ""), new TableColumn("at", "timestamptz", true, "now()") is var at ? (at.NullText, at.DefaultText, at.KeyText) : default);
        Assert.Equal("", new TableColumn("x", "text", true, null).DefaultText);
    }

    [Fact]
    public void Common_types_are_offered_first_with_text()
    {
        Assert.Equal("text", PostgresSql.CommonTypes[0]);
        Assert.Contains("jsonb", PostgresSql.CommonTypes);
    }
}
