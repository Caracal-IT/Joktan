using System.Collections.Generic;
using System.Linq;
using System.Text;
using Joktan.Data.Resources;

namespace Joktan.Data.Postgres;

/// <summary>A column of a table, as information_schema gives it.</summary>
/// <param name="Type">The type as PostgreSQL writes it, such as "character varying(20)".</param>
/// <param name="Default">The default expression, or null for none.</param>
public sealed record TableColumn(string Name, string Type, bool IsNullable, string? Default, bool IsPrimaryKey = false, bool IsIdentity = false)
{
    /// <summary>Whether it may be NULL, as shown in the columns' table.</summary>
    public string NullText => IsNullable ? Strings.TableColumn_Yes : Strings.TableColumn_No;

    /// <summary>Its default, or that it is numbered for each row.</summary>
    public string DefaultText => IsIdentity ? Strings.TableColumn_NumberedForEachRow : Default ?? "";

    /// <summary>"primary key", or empty.</summary>
    public string KeyText => IsPrimaryKey ? Strings.TableColumn_PrimaryKey : "";
}

/// <summary>A column to add to a table.</summary>
/// <param name="Default">An SQL expression for the default, or empty for none.</param>
public sealed record ColumnSpec(string Name, string Type, bool NotNull = false, string Default = "");

/// <summary>A row read from a table: its ctid, which names it for deleting, and each column's value as text, null for NULL.</summary>
public sealed record TableRow(string Id, IReadOnlyList<string?> Values);

/// <summary>
/// The SQL the database browser on Data / Database sends. Names are always quoted, so any name
/// PostgreSQL accepts can be used; values are always parameters, never part of the text.
/// </summary>
public static class PostgresSql
{
    /// <summary>The types offered for a new column. Any other type PostgreSQL knows can be typed.</summary>
    public static readonly IReadOnlyList<string> CommonTypes =
        ["text", "varchar(255)", "integer", "bigint", "numeric", "double precision", "boolean", "date", "timestamptz", "uuid", "jsonb", "bytea"];

    /// <summary>A name in double quotes, with any double quote in it doubled.</summary>
    public static string Quote(string name) => "\"" + name.Replace("\"", "\"\"") + "\"";

    public static string Table(string schema, string table) => Quote(schema) + "." + Quote(table);

    /// <summary>The user's own schemas, without PostgreSQL's.</summary>
    public const string Schemas = """
        SELECT nspname FROM pg_catalog.pg_namespace
        WHERE nspname <> 'information_schema' AND nspname NOT LIKE 'pg\_%'
        ORDER BY nspname
        """;

    /// <summary>The tables of the schema in parameter 1.</summary>
    public const string Tables = """
        SELECT table_name FROM information_schema.tables
        WHERE table_schema = $1 AND table_type = 'BASE TABLE'
        ORDER BY table_name
        """;

    /// <summary>The columns of the table in parameters 1 (schema) and 2 (table), in order, with whether each is in the primary key.</summary>
    public const string Columns = """
        SELECT c.column_name, pg_catalog.format_type(a.atttypid, a.atttypmod), c.is_nullable = 'YES', c.column_default,
               EXISTS (SELECT 1 FROM pg_catalog.pg_index i WHERE i.indrelid = a.attrelid AND i.indisprimary AND a.attnum = ANY (i.indkey)),
               c.is_identity = 'YES'
        FROM information_schema.columns c
        JOIN pg_catalog.pg_attribute a
          ON a.attrelid = pg_catalog.format('%I.%I', c.table_schema, c.table_name)::regclass AND a.attname = c.column_name
        WHERE c.table_schema = $1 AND c.table_name = $2
        ORDER BY c.ordinal_position
        """;

    public static string CreateSchema(string name) => $"CREATE SCHEMA {Quote(name)}";

    /// <summary>A new table, with an id column that numbers its rows if asked for.</summary>
    public static string CreateTable(string schema, string name, bool withId)
        => withId
            ? $"CREATE TABLE {Table(schema, name)} (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)"
            : $"CREATE TABLE {Table(schema, name)} ()";

    /// <summary>Adds a column. Its type and default are SQL, as typed; its name is quoted.</summary>
    public static string AddColumn(string schema, string table, ColumnSpec column)
    {
        var text = new StringBuilder($"ALTER TABLE {Table(schema, table)} ADD COLUMN {Quote(column.Name)} {column.Type.Trim()}");
        if (column.Default.Trim().Length > 0)
            text.Append(" DEFAULT ").Append(column.Default.Trim());
        if (column.NotNull)
            text.Append(" NOT NULL");
        return text.ToString();
    }

    /// <summary>
    /// A page of a table's rows, each column as text, after its ctid. They are in the order of
    /// <paramref name="orderBy"/>, its primary key, or else of ctid, so that pages do not overlap.
    /// </summary>
    public static string SelectRows(string schema, string table, IEnumerable<string> columns, IReadOnlyList<string> orderBy, int limit, int offset)
    {
        var list = columns.Select(c => Quote(c) + "::text").Prepend("ctid::text");
        var order = orderBy.Count > 0 ? string.Join(", ", orderBy.Select(Quote)) : "ctid";
        return $"SELECT {string.Join(", ", list)} FROM {Table(schema, table)} ORDER BY {order} LIMIT {limit} OFFSET {offset}";
    }

    public static string Count(string schema, string table) => $"SELECT count(*) FROM {Table(schema, table)}";

    /// <summary>
    /// Inserts one row with the columns given, each value parameter $1, $2 and so on, sent as text
    /// for PostgreSQL to read as the column's type. With no columns, a row of defaults.
    /// </summary>
    public static string Insert(string schema, string table, IReadOnlyList<string> columns)
        => columns.Count == 0
            ? $"INSERT INTO {Table(schema, table)} DEFAULT VALUES"
            : $"INSERT INTO {Table(schema, table)} ({string.Join(", ", columns.Select(Quote))}) VALUES ({string.Join(", ", columns.Select((_, i) => $"${i + 1}"))})";

    /// <summary>
    /// Changes the columns given of the row whose ctid is the last parameter, each value parameter
    /// $1, $2 and so on, sent as text for PostgreSQL to read as the column's type.
    /// </summary>
    public static string Update(string schema, string table, IReadOnlyList<string> columns)
        => $"UPDATE {Table(schema, table)} SET {string.Join(", ", columns.Select((c, i) => $"{Quote(c)} = ${i + 1}"))} WHERE ctid = ${columns.Count + 1}::tid";

    /// <summary>Drops a schema with everything in it.</summary>
    public static string DropSchema(string name) => $"DROP SCHEMA {Quote(name)} CASCADE";

    /// <summary>Drops a table, and the views and keys that depend on it.</summary>
    public static string DropTable(string schema, string table) => $"DROP TABLE {Table(schema, table)} CASCADE";

    /// <summary>Drops a column, and the views and keys that depend on it.</summary>
    public static string DropColumn(string schema, string table, string column) => $"ALTER TABLE {Table(schema, table)} DROP COLUMN {Quote(column)} CASCADE";

    /// <summary>Deletes the row whose ctid is parameter 1.</summary>
    public static string Delete(string schema, string table) => $"DELETE FROM {Table(schema, table)} WHERE ctid = $1::tid";
}
