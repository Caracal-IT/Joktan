using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using Joktan.Data.Postgres;
using Joktan.Users.Model;

namespace Joktan.Users;

/// <summary>Why the users or roles could not be read or changed, in words that can be shown.</summary>
public sealed class UserStoreException(string message) : Exception(message);

/// <summary>
/// The users and roles in the tables <c>joktan.roles</c> and <c>joktan.users</c> of a PostgreSQL database.
/// Each statement gives one text value, rows as JSON, through <see cref="IDatabaseConnection.RunAsync"/>;
/// values are parameters. Owns the connection it is given.
/// </summary>
/// <param name="schema">The schema holding the tables; tests give one of their own.</param>
public sealed class PostgresUserStore(IDatabaseConnection connection, string schema = PostgresUserStore.DefaultSchema) : IUserStore
{
    public const string DefaultSchema = "joktan";

    private readonly string Schema = PostgresSql.Quote(schema);

    private const string RoleJson = "json_build_object('id', id, 'name', name, 'description', description, 'built_in', built_in)";

    private const string UserJson = "json_build_object('id', id, 'username', username, 'email', email, 'has_password', password_hash <> '', 'first_name', first_name, 'last_name', last_name, 'description', description, 'notes', notes, 'role_id', role_id)";

    /// <summary>The statements that make the schema and its tables if they are not there, then say whether there are no roles yet.</summary>
    public IReadOnlyList<SqlText> SetUpStatements =>
    [
        new($"CREATE SCHEMA IF NOT EXISTS {Schema}", []),
        new($"""
             CREATE TABLE IF NOT EXISTS {Schema}.roles (
                 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 name text NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
                 description text NOT NULL DEFAULT '',
                 built_in boolean NOT NULL DEFAULT false,
                 created timestamptz NOT NULL DEFAULT now(),
                 changed timestamptz NOT NULL DEFAULT now())
             """, []),
        new($"""
             CREATE TABLE IF NOT EXISTS {Schema}.users (
                 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 username text,
                 email text NOT NULL DEFAULT '',
                 password_hash text NOT NULL DEFAULT '',
                 first_name text NOT NULL CHECK (length(trim(first_name)) > 0),
                 last_name text NOT NULL CHECK (length(trim(last_name)) > 0),
                 description text NOT NULL DEFAULT '',
                 notes text NOT NULL DEFAULT '',
                 role_id integer NOT NULL REFERENCES {Schema}.roles (id) ON DELETE RESTRICT,
                 created timestamptz NOT NULL DEFAULT now(),
                 changed timestamptz NOT NULL DEFAULT now())
             """, []),
        // Tables made before users had a username, email and password are given them; a username is made from the name.
        new($"ALTER TABLE {Schema}.users ADD COLUMN IF NOT EXISTS username text", []),
        new($"ALTER TABLE {Schema}.users ADD COLUMN IF NOT EXISTS email text NOT NULL DEFAULT ''", []),
        new($"ALTER TABLE {Schema}.users ADD COLUMN IF NOT EXISTS password_hash text NOT NULL DEFAULT ''", []),
        new($"UPDATE {Schema}.users SET username = lower(first_name || '.' || last_name) || '.' || id WHERE username IS NULL OR trim(username) = ''", []),
        new($"ALTER TABLE {Schema}.users ALTER COLUMN username SET NOT NULL", []),
        new($"CREATE UNIQUE INDEX IF NOT EXISTS users_username ON {Schema}.users (lower(username))", []),
        new($"SELECT (NOT EXISTS (SELECT 1 FROM {Schema}.roles))::text", []),
    ];

    /// <summary>The statements that give a new database the recommended roles, then the default administrator.</summary>
    public IReadOnlyList<SqlText> SeedStatements()
    {
        var statements = RecommendedRoles.All
            .Select(r => new SqlText($"INSERT INTO {Schema}.roles (name, description, built_in) VALUES ($1, $2, $3) ON CONFLICT (name) DO NOTHING RETURNING id::text",
                [r.Name, r.Description, r.BuiltIn ? "true" : "false"]))
            .ToList();
        var admin = RecommendedRoles.DefaultAdministrator;
        statements.Add(new($"INSERT INTO {Schema}.users (username, first_name, last_name, description, notes, role_id) SELECT $1, $2, $3, $4, $5, id FROM {Schema}.roles WHERE name = $6 RETURNING id::text",
            [admin.Username, admin.FirstName, admin.LastName, admin.Description, admin.Notes, RecommendedRoles.Administrator]));
        return statements;
    }

    public async Task<bool> SetUpAsync(CancellationToken cancel = default)
    {
        var empty = (await connection.RunAsync(SetUpStatements, cancel))[^1] == "true";
        if (empty)
            await connection.RunAsync(SeedStatements(), cancel);
        return empty;
    }

    public async Task<IReadOnlyList<Role>> RolesAsync(CancellationToken cancel = default)
        => Read<List<Role>>(await One(new($"SELECT coalesce(json_agg({RoleJson} ORDER BY built_in DESC, lower(name)), '[]')::text FROM {Schema}.roles", []), cancel)) ?? [];

    public async Task<IReadOnlyList<User>> UsersAsync(CancellationToken cancel = default)
        => Read<List<User>>(await One(new($"SELECT coalesce(json_agg({UserJson} ORDER BY lower(last_name), lower(first_name), id), '[]')::text FROM {Schema}.users", []), cancel)) ?? [];

    public async Task<Role> SaveRoleAsync(Role role, CancellationToken cancel = default)
    {
        // The Administrator role keeps its name; its description can change.
        var statement = role.Id == 0
            ? new SqlText($"INSERT INTO {Schema}.roles (name, description) VALUES ($1, $2) RETURNING {RoleJson}::text", [role.Name.Trim(), role.Description.Trim()])
            : new SqlText($"UPDATE {Schema}.roles SET name = CASE WHEN built_in THEN name ELSE $1 END, description = $2, changed = now() WHERE id = $3 RETURNING {RoleJson}::text",
                [role.Name.Trim(), role.Description.Trim(), Id(role.Id)]);
        return Read<Role>(await One(statement, cancel)) ?? throw new UserStoreException("The role has gone; it may have been removed.");
    }

    public async Task DeleteRoleAsync(int id, CancellationToken cancel = default)
    {
        if (await One(new($"DELETE FROM {Schema}.roles WHERE id = $1 AND NOT built_in RETURNING id::text", [Id(id)]), cancel) == "")
            throw new UserStoreException("The role could not be removed: it is the Administrator role, or it has gone.");
    }

    public async Task<User> SaveUserAsync(User user, CancellationToken cancel = default)
    {
        // A password is only ever sent hashed; none given keeps the one there is.
        var hash = user.NewPassword is { Length: > 0 } password ? PasswordHasher.Hash(password) : null;
        string?[] values = [user.Username.Trim(), user.Email.Trim(), user.FirstName.Trim(), user.LastName.Trim(), user.Description.Trim(), user.Notes.Trim(), Id(user.RoleId), hash];
        var statement = user.Id == 0
            ? new SqlText($"INSERT INTO {Schema}.users (username, email, first_name, last_name, description, notes, role_id, password_hash) VALUES ($1, $2, $3, $4, $5, $6, $7, coalesce($8, '')) RETURNING {UserJson}::text", values)
            : new SqlText($"UPDATE {Schema}.users SET username = $1, email = $2, first_name = $3, last_name = $4, description = $5, notes = $6, role_id = $7, password_hash = coalesce($8, password_hash), changed = now() WHERE id = $9 RETURNING {UserJson}::text",
                [.. values, Id(user.Id)]);
        return Read<User>(await One(statement, cancel)) ?? throw new UserStoreException("The user has gone; they may have been removed.");
    }

    /// <summary>Whether the user with this username has this password; for signing in.</summary>
    public async Task<bool> CheckPasswordAsync(string username, string password, CancellationToken cancel = default)
        => PasswordHasher.Verify(password, await One(new($"SELECT password_hash FROM {Schema}.users WHERE lower(username) = lower($1)", [username.Trim()]), cancel));

    public async Task DeleteUserAsync(int id, CancellationToken cancel = default)
        => await One(new($"DELETE FROM {Schema}.users WHERE id = $1 RETURNING id::text", [Id(id)]), cancel);

    private static string Id(int id) => id.ToString(CultureInfo.InvariantCulture);

    private async Task<string> One(SqlText statement, CancellationToken cancel) => (await connection.RunAsync([statement], cancel))[0];

    private static T? Read<T>(string json) where T : class => json.Length == 0 ? null : JsonSerializer.Deserialize<T>(json);

    public ValueTask DisposeAsync() => connection.DisposeAsync();
}
